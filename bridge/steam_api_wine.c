// ─── vgui2.dll runtime CRT patch ─────────────────────────────────────────────
// L4D2's vgui2.dll has a CRT helper that lazily resolves FlsAlloc/FlsSetValue/
// FlsGetValue/FlsFree via GetModuleHandleW("KERNEL32.DLL") + GetProcAddress,
// stores them as MSVC-encoded pointers in its .data, then calls them through
// `call *eax` later. On Wine 7.7 that init never runs (or returns the wrong
// handle), so the slots stay NULL and the game crashes with EIP=0 ~6s in,
// deep inside vgui2's per-thread-data lookup at +0x35567.
//
// We hot-patch the slots ourselves the first time the game calls SteamAPI
// after vgui2 is loaded: find vgui2's base, locate the 4 encoded-pointer
// slots, EncodePointer the real Wine FlsXxx exports, write them in.
static int g_vgui2_patched = 0;

static void *encode_ptr(HMODULE k32, void *p) {
    typedef void *(__stdcall *encode_t)(void *);
    encode_t enc = (encode_t)GetProcAddress(k32, "EncodePointer");
    return enc ? enc(p) : p;
}

// Catch-all stub for any encoded function pointer vgui2 may try to invoke.
// Just returns 0 — most CRT helpers (e.g. __dllonexit) can no-op safely.
// Declared as a wide cdecl: accepts up to 8 ints, ignores them, returns 0.
static int __attribute__((cdecl)) noop_handler(int a, int b, int c, int d, int e, int f, int g, int h) {
    (void)a;(void)b;(void)c;(void)d;(void)e;(void)f;(void)g;(void)h;
    return 0;
}

