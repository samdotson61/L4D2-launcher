// Debug logging gate.  -1 = not yet checked, 0 = off, 1 = on.  Controlled by
// the L4D2_BRIDGE_DEBUG environment variable (set to "1" to enable the
// Z:\tmp\bridge.log trace).  Off by default so shipping builds don't pay the
// per-call CreateFile/WriteFile cost or fill the disk with traces.
static int g_dbg_enabled = -1;

static void dbg(const char *fmt, ...) {
    if (g_dbg_enabled < 0) {
        char ev[8] = {0};
        DWORD got = GetEnvironmentVariableA("L4D2_BRIDGE_DEBUG", ev, sizeof ev);
        g_dbg_enabled = (got > 0 && ev[0] == '1') ? 1 : 0;
    }
    if (!g_dbg_enabled) return;

    char buf[512];
    va_list ap; va_start(ap, fmt);
    int n = wvsprintfA(buf, fmt, ap); va_end(ap);
    OutputDebugStringA(buf);
    // Also append to a Wine-side log file so we can grep it from macOS without
    // turning on the full WINEDEBUG stream (which would drown the engine logs).
    HANDLE h = CreateFileA("Z:\\tmp\\bridge.log", FILE_APPEND_DATA, FILE_SHARE_READ|FILE_SHARE_WRITE,
                           NULL, OPEN_ALWAYS, FILE_ATTRIBUTE_NORMAL, NULL);
    if (h != INVALID_HANDLE_VALUE) {
        DWORD wrote;
        WriteFile(h, buf, (DWORD)n, &wrote, NULL);
        CloseHandle(h);
    }
}

static int rpc_connect(void) {
    WSADATA wsa;
    if (WSAStartup(MAKEWORD(2,2), &wsa) != 0) return -1;
    g_sock = socket(AF_INET, SOCK_STREAM, 0);
    if (g_sock == INVALID_SOCKET) return -1;
    int one = 1;
    setsockopt(g_sock, IPPROTO_TCP, TCP_NODELAY, (const char*)&one, sizeof one);
    struct sockaddr_in addr;
    addr.sin_family = AF_INET;
    addr.sin_port = htons(54550);
    addr.sin_addr.s_addr = htonl(0x7F000001);
    if (connect(g_sock, (struct sockaddr*)&addr, sizeof addr) < 0) {
        closesocket(g_sock); g_sock = INVALID_SOCKET; return -1;
    }
    dbg("[bridge] helper connected\n");
    return 0;
}
static int send_all(const void *buf, int n) {
    const char *p = (const char *)buf; int sent = 0;
    while (sent < n) { int s = send(g_sock, p + sent, n - sent, 0); if (s <= 0) return -1; sent += s; }
    return 0;
}
static int recv_all(void *buf, int n) {
    char *p = (char *)buf; int got = 0;
    while (got < n) { int r = recv(g_sock, p + got, n - got, 0); if (r <= 0) return -1; got += r; }
    return 0;
}
static int rpc_call(u32 op, const void *arg, u32 arg_len, void *out, u32 out_max) {
    if (g_lock_init) EnterCriticalSection(&g_rpc_lock);
    if (g_sock == INVALID_SOCKET && rpc_connect() < 0) {
        if (g_lock_init) LeaveCriticalSection(&g_rpc_lock);
        return -1;
    }
    u32 hdr[2]; hdr[0] = op; hdr[1] = arg_len;
    u32 resp[2] = {0,0};
    u32 rlen = 0;
    if (send_all(hdr, sizeof hdr) < 0) goto fail;
    if (arg_len && send_all(arg, arg_len) < 0) goto fail;
    if (recv_all(resp, sizeof resp) < 0) goto fail;
    rlen = resp[1];
    if (rlen > 0 && rlen <= out_max) {
        if (recv_all(out, rlen) < 0) goto fail;
    } else if (rlen > out_max) {
        char trash[64]; u32 rem = rlen;
        while (rem) { u32 t = rem > sizeof trash ? sizeof trash : rem;
                      if (recv_all(trash, t) < 0) goto fail; rem -= t; }
        rlen = 0;
    }
    if (g_lock_init) LeaveCriticalSection(&g_rpc_lock);
    return resp[0] == 0 ? (int)rlen : -1;
fail:
    closesocket(g_sock); g_sock = INVALID_SOCKET;
    if (g_lock_init) LeaveCriticalSection(&g_rpc_lock);
    return -1;
}
static u32 rpc_u32_(u32 op, const void *arg, u32 alen) {
    u32 v = 0; rpc_call(op, arg, alen, &v, sizeof v); return v;
}
static u64 rpc_u64_(u32 op, const void *arg, u32 alen) {
    u64 v = 0; rpc_call(op, arg, alen, &v, sizeof v); return v;
}
static const char *rpc_str_(u32 op, char *dest, size_t dlen, const void *arg, u32 alen) {
    int n = rpc_call(op, arg, alen, dest, dlen - 1);
    if (n < 0) { dest[0] = 0; return dest; }
    if ((unsigned)n >= dlen) n = (int)(dlen - 1);
    dest[n] = 0; return dest;
}
