// steam_api_wine.c — Wine PE32 i386 steam_api.dll bridge.
//
// Pure C, no C++ statics, no CRT. All vtables initialized at link time so
// the DLL loads with valid vptrs without a CRT-driven constructor pass.
//
// Strategy:
//   - Engine.dll calls our exports (SteamAPI_Init, SteamInternal_*, etc.).
//   - SteamAPI_Init forwards to a native macOS helper over TCP, which talks
//     to the running signed-in Mac Steam (steam_osx) via libsteam_api.dylib.
//   - SteamInternal_ContextInit invokes the engine-side init thunks so each
//     CSteamAPIContext slot ends up holding a pointer to one of our stub
//     objects.
//   - Each interface (ISteamUser, ISteamApps, etc.) is a struct whose first
//     member is a vtable pointer. The vtables are auto-generated by
//     `gen_vtables.py` from the Steamworks SDK headers so every method has
//     the CORRECT __thiscall arg count — `ret N` cleans the stack exactly
//     the way engine.dll expects.
//   - For the handful of methods L4D2 actually needs to read real data
//     from (SteamID, persona name, ownership, etc.) we provide RPC-backed
//     implementations and reference them from the generated vtables via
//     the REAL_IMPLS map in the generator.

