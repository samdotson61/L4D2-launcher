// SteamInternal_ContextInit: engine-side init thunk dispatcher.
struct ctx_init_spec {
    void (__cdecl *ctor_fn)(void **slot);
    void *result_slot;
    void *pad;
};
__declspec(dllexport) void* SteamInternal_ContextInit(void* pContextInitData) {
    struct ctx_init_spec *s = (struct ctx_init_spec *)pContextInitData;
    if (!s) return 0;
    if (!s->result_slot && s->ctor_fn) s->ctor_fn(&s->result_slot);
    return &s->result_slot;
}

