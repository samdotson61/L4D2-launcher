// ─── Mini libc (no UCRT dep) ────────────────────────────────────────────────
static int my_strncmp(const char* a, const char* b, size_t n) {
    for (size_t i = 0; i < n; i++) {
        unsigned char ca = (unsigned char)a[i], cb = (unsigned char)b[i];
        if (ca != cb) return ca - cb;
        if (ca == 0) return 0;
    }
    return 0;
}
static void my_memcpy(void* d, const void* s, size_t n) {
    char* dp = (char*)d; const char* sp = (const char*)s;
    while (n--) *dp++ = *sp++;
}
// GCC implicitly emits memcpy/memset calls for larger struct copies and
// initializers — provide standalone definitions so -nodefaultlibs links
// cleanly without dragging in MSVCRT.
void* memcpy(void* d, const void* s, size_t n) {
    my_memcpy(d, s, n);
    return d;
}
void* memset(void* d, int c, size_t n) {
    unsigned char* dp = (unsigned char*)d;
    while (n--) *dp++ = (unsigned char)c;
    return d;
}
// GCC emits __chkstk_ms calls for functions with stack allocations larger
// than ~4KB (probe pages so the guard page actually fires).  Wine doesn't
// use guard pages the same way; we have plenty of stack, so a no-op is
// safe.  Called with stack-size-to-probe in %eax — no return value.
__attribute__((naked)) void __chkstk_ms(void) {
    __asm__("ret");
}

