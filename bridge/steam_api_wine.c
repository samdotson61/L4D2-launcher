// Per call to SteamAPI_RunCallbacks. Drain REAL callbacks from native Mac
// Steam via the helper's OP_DRAIN_CALLBACKS RPC, then dispatch each to any
// registered handlers tracked by cb_register().
//
// The drain returns a packed blob:
//   [n_cb:u32] N*{ id:u32, data_len:u32, data:bytes }
//
// We don't fake-fire anything anymore — only callbacks that real Steam
// actually delivered get dispatched. This gives the engine real Steam
// state (LobbyEnter_t, UserStatsReceived_t, friend updates, etc.) so the
// state machines that gated level load are now driven by truth, not by
// our guesses.
static unsigned char g_drain_buf[32768];

static void deliver_pending_callbacks(void) {
    g_runcb_tick++;
    // Drain every 2nd tick — fast enough to keep state-machines moving but
    // doesn't churn the RPC channel.
    if ((g_runcb_tick & 1) != 0) return;

    int n_signed = rpc_call(OP_DRAIN_CALLBACKS, 0, 0, g_drain_buf, sizeof g_drain_buf);
    if (n_signed < 4) return;
    // n is now a safe upper bound on accessible bytes in g_drain_buf.  Use
    // size_t to make every offset comparison overflow-immune.
    size_t n = (size_t)n_signed;
    unsigned n_cb = 0;
    memcpy(&n_cb, g_drain_buf, 4);
    if (!n_cb) return;
    dbg("[bridge] drain: %u callbacks (%u bytes)\n", n_cb, (unsigned)n);
    size_t off = 4;
    for (unsigned i = 0; i < n_cb; i++) {
        // Overflow-safe bound check: was `off+8 > n` and `off+dlen > n` —
        // those WRAP on huge dlen and let garbage offsets through, which
        // crashes the loop a few iterations later at g_drain_buf+off+4.
        // Use subtraction so the check stays sound for any dlen value.
        if (n < 8 || off > n - 8) break;
        unsigned id = 0, dlen = 0;
        memcpy(&id,   g_drain_buf + off,     4);
        memcpy(&dlen, g_drain_buf + off + 4, 4);
        off += 8;
        if (dlen > n - off) break;  // payload won't fit — malformed; stop

        // Special envelope: 0xFFFFFFFE marks a CCallResult delivery.
        // Payload layout: { realId:u32, hAsyncCall:u64, bFailed:u32, data:bytes }
        if (id == 0xFFFFFFFEu) {
            if (dlen < 16) { off += dlen; continue; }
            unsigned realId = 0, bFailed = 0;
            u64 hAsyncCall = 0;
            memcpy(&realId,     g_drain_buf + off,     4);
            memcpy(&hAsyncCall, g_drain_buf + off + 4, 8);
            memcpy(&bFailed,    g_drain_buf + off + 12, 4);
            void *data = (dlen > 16) ? (void*)(g_drain_buf + off + 16) : NULL;
            // Decode key callback structs for diagnostics.
            if (data) {
                u8 *d = (u8*)data;
                if (realId == 504) {  // LobbyEnter_t
                    u64 sidLobby; my_memcpy(&sidLobby, d, 8);
                    u32 chatPerms, resp; my_memcpy(&chatPerms, d + 8, 4);
                    // m_bLocked at +12 (1 byte) + 3 pad, then m_EChatRoomEnterResponse at +16
                    my_memcpy(&resp, d + 16, 4);
                    const char* reason = "?";
                    switch (resp) {
                      case 1: reason="Success"; break;
                      case 2: reason="DoesntExist"; break;
                      case 3: reason="NotAllowed"; break;
                      case 4: reason="Full"; break;
                      case 5: reason="Error"; break;
                      case 6: reason="Banned"; break;
                      case 7: reason="Limited"; break;
                      case 8: reason="ClanDisabled"; break;
                      case 9: reason="CommunityBan"; break;
                      case 10: reason="MemberBlockedYou"; break;
                      case 11: reason="YouBlockedMember"; break;
                      case 12: reason="NoRankingDataLobby"; break;
                      case 13: reason="NoRankingDataUser"; break;
                      case 14: reason="RankOutOfRange"; break;
                    }
                    dbg("[bridge] LobbyEnter_t: lobby=%08lx:%08lx resp=%u (%s)\n",
                        (unsigned long)(sidLobby >> 32), (unsigned long)(sidLobby & 0xFFFFFFFF),
                        resp, reason);
                } else if (realId == 513) {  // LobbyCreated_t
                    u32 result; my_memcpy(&result, d, 4);
                    u64 sidLobby; my_memcpy(&sidLobby, d + 8, 8);
                    dbg("[bridge] LobbyCreated_t: result=%u lobby=%08lx:%08lx\n",
                        result, (unsigned long)(sidLobby >> 32), (unsigned long)(sidLobby & 0xFFFFFFFF));
                } else if (realId == 510) {  // LobbyMatchList_t
                    u32 n; my_memcpy(&n, d, 4);
                    dbg("[bridge] LobbyMatchList_t: %u lobbies matched\n", n);
                }
            }
            // Some games also register a CCallback for the same id; fire both
            // paths so whichever handler the game uses receives the data.
            cr_fire(hAsyncCall, data, (int)bFailed);
            cb_fire((int)realId, data);
            off += dlen;
            continue;
        }

        // Callback blacklist for early-init events whose engine handlers
        // require ENGINE-SIDE state we can't initialize from the bridge:
        //
        // - id=304 (PersonaStateChange_t): engine's friends-list cache
        //   isn't populated in our env; the handler walks an
        //   uninitialized list and dies on a NULL deref.  Bridge's
        //   GetFriendPersonaName/RequestUserInformation already resolve
        //   friend data on-demand from real Steam, so PSC is redundant.
        //
        // - id=1101 (UserStatsReceived_t): triggers a NULL-vtable call
        //   in the stats-update path (engine.dll+0x190A9D), which we
        //   don't have a clean way to short-circuit.
        //
        // 2026-05-26: id=101 (SteamServersConnected_t) un-blacklisted —
        // game hosting flow stalls on "Creating a new public game..."
        // without it (needs "online ready" signal to advertise lobby).
        // Original crash from delivering 101 was the corrupted-vtable
        // crash at engine.dll+0x83ce8, which was a downstream symptom of
        // the ABI / IAT-zero issues we've since fixed.
        int skip = 0;
        switch ((int)id) {
            case 304: case 1101: skip = 1; break;
            default: break;
        }
        // Matchmaking callback gate (id range 500-599): until the game has
        // actually called a matchmaking op (mm_RequestLobbyList et al), the
        // game has no lobby state and its handlers will crash on deref.
        // After the gate opens, callbacks flow normally.
        if (!skip && id >= 500 && id < 600 && !g_mm_engaged) {
            dbg("[bridge] drain: gating matchmaking callback id=%u (mm not engaged)\n", id);
            skip = 1;
        }
        if (!skip) {
            // Diagnostic log for low-volume / important IDs (auth-related
            // 143 = ValidateAuthTicketResponse_t, matchmaking 500-520,
            // game server 200-219).  Skips high-volume IDs (502 lobby data
            // update fires hundreds of times per minute in a populated lobby).
            if (id == 143 || (id >= 200 && id < 220) || (id >= 500 && id < 520 && id != 502)) {
                // For ValidateAuthTicketResponse_t, decode the response field
                // (offset 8) so we can see exactly why Steam rejected.
                if (id == 143 && dlen >= 12) {
                    u64 sidUser; my_memcpy(&sidUser, g_drain_buf + off, 8);
                    u32 resp; my_memcpy(&resp, g_drain_buf + off + 8, 4);
                    const char* name = "?";
                    switch (resp) {
                      case 0: name="OK"; break;
                      case 1: name="UserNotConnectedToSteam"; break;
                      case 2: name="NoLicenseOrExpired"; break;
                      case 3: name="VACBanned"; break;
                      case 4: name="LoggedInElseWhere"; break;
                      case 5: name="VACCheckTimedOut"; break;
                      case 6: name="AuthTicketCanceled"; break;
                      case 7: name="AuthTicketInvalidAlreadyUsed"; break;
                      case 8: name="AuthTicketInvalid"; break;
                      case 9: name="PublisherIssuedBan"; break;
                    }
                    dbg("[bridge] drain: ValidateAuthTicketResponse_t sid=%08lx:%08lx resp=%u (%s)\n",
                        (unsigned long)(sidUser >> 32), (unsigned long)(sidUser & 0xFFFFFFFF),
                        resp, name);
                } else {
                    dbg("[bridge] drain: fire id=%u dlen=%u\n", id, dlen);
                }
            }
            cb_fire((int)id, dlen ? (void*)(g_drain_buf + off) : NULL);
        } else {
            dbg("[bridge] drain: skipped callback id=%u (blacklisted)\n", id);
        }
        off += dlen;
    }
}

// ── Background IAT watcher ─────────────────────────────────────────────────
// Something inside the matchmaking flow zeros engine.dll's IAT entries for
// steam_api exports (deterministic — same crash every time, EBX=0 after
// `mov 0x1034e3f0,%ebx` in engine's BlockingCall wait loop).  The zeroing
// is NOT FreeLibrary (pinning the library +3 refcount didn't prevent it,
// no DLL has a direct write to that address, and engine.dll has no
// FreeLibrary call referenced).  Most likely: Source DRM signature check
// or matchmaking defensive cleanup using a computed address.
//
// Counter-measure: a dedicated thread that polls engine.dll's IAT for our
// exports every millisecond.  When it sees a slot zero out, it restores
// from our DLL's exports.  Engine.dll's next main-loop tick (~16ms later)
// then dispatches through the restored slot.
//
// We can't run this inline from a Steam entry point — adding the same
// check to SteamAPI_IsSteamRunning broke SP campaign load, likely because
// the per-tick GetModuleHandleA / pointer-deref overhead racing with
// engine.dll init was unstable.  A dedicated thread runs outside that
// path entirely.
struct iat_slot { unsigned offset; const char* exp_name; void *cached_target; };
static struct iat_slot g_iat_slots[] = {
    { 0x34E3EC, "SteamAPI_Init",                NULL },
    { 0x34E3F0, "SteamAPI_RunCallbacks",        NULL },
    { 0x34E3F4, "SteamAPI_UnregisterCallback",  NULL },
    { 0x34E3F8, "SteamAPI_RegisterCallback",    NULL },
};
static HMODULE g_self_hmodule = NULL;
static HMODULE g_engine_hmodule = NULL;
static volatile int g_iat_watcher_run = 0;

// Hot-patch the two engine.dll instructions that reference IAT slot
// 0x1034e3f0 (SteamAPI_RunCallbacks).  Previous version redirected to a
// static bypass pointer — but the IAT-zeroing writer follows the pointer
// chain and zeros our static too.  New version uses DIRECT addressing:
// rewrite the instructions so the function pointer is embedded directly
// in engine.dll's CODE, eliminating any memory location for the writer
// to target.
//
//   Site 1 (call):  ff 15 [iat_abs]   →  e8 [rel32] 90      (call direct)
//   Site 2 (mov):   8b 1d [iat_abs]   →  bb [funcptr] 90    (mov immediate)
//
// Both rewrites keep the same 6-byte instruction length, so no code shift.
static void patch_engine_runcb_refs(void) {
    void *runcb = (void*)GetProcAddress(g_self_hmodule, "SteamAPI_RunCallbacks");
    if (!runcb) {
        dbg("[bridge] patch_engine_runcb: SteamAPI_RunCallbacks export missing!\n");
        return;
    }
    unsigned expected = 0x1034e3f0u + ((unsigned)g_engine_hmodule - 0x10000000u);

    // Site 1: engine.dll+0x83a07 — `ff 15 [imm32]` → `e8 [rel32] 90`
    //   rel32 is computed relative to (site + 5), the end of the call.
    {
        unsigned char *site = (unsigned char*)g_engine_hmodule + 0x83a07;
        unsigned char expected_hdr[6] = {0xff, 0x15, 0,0,0,0};
        memcpy(expected_hdr + 2, &expected, 4);
        if (memcmp(site, expected_hdr, 6) != 0) {
            unsigned actual_imm;
            memcpy(&actual_imm, site + 2, 4);
            dbg("[bridge] patch_engine_runcb: site 1 unexpected — hdr=%02x %02x imm32=0x%x (expected 0x%x)\n",
                site[0], site[1], actual_imm, expected);
        } else {
            unsigned rel32 = (unsigned)((char*)runcb - (char*)(site + 5));
            DWORD oldprot;
            if (VirtualProtect(site, 6, PAGE_EXECUTE_READWRITE, &oldprot)) {
                site[0] = 0xe8;                // direct call
                memcpy(site + 1, &rel32, 4);   // PC-relative target
                site[5] = 0x90;                // NOP pad
                DWORD ignore;
                VirtualProtect(site, 6, oldprot, &ignore);
                FlushInstructionCache(GetCurrentProcess(), site, 6);
                dbg("[bridge] patch_engine_runcb: site 1 → e8 rel32 90  (target=%p rel32=0x%x)\n",
                    runcb, rel32);
            }
        }
    }

    // Site 2: engine.dll+0x18cea8 — `8b 1d [imm32]` → `bb [imm32:funcptr] 90`
    {
        unsigned char *site = (unsigned char*)g_engine_hmodule + 0x18cea8;
        unsigned char expected_hdr[6] = {0x8b, 0x1d, 0,0,0,0};
        memcpy(expected_hdr + 2, &expected, 4);
        if (memcmp(site, expected_hdr, 6) != 0) {
            unsigned actual_imm;
            memcpy(&actual_imm, site + 2, 4);
            dbg("[bridge] patch_engine_runcb: site 2 unexpected — hdr=%02x %02x imm32=0x%x (expected 0x%x)\n",
                site[0], site[1], actual_imm, expected);
        } else {
            unsigned funcptr_imm = (unsigned)runcb;
            DWORD oldprot;
            if (VirtualProtect(site, 6, PAGE_EXECUTE_READWRITE, &oldprot)) {
                site[0] = 0xbb;                       // mov $imm32, %ebx
                memcpy(site + 1, &funcptr_imm, 4);    // function pointer literal
                site[5] = 0x90;                        // NOP pad
                DWORD ignore;
                VirtualProtect(site, 6, oldprot, &ignore);
                FlushInstructionCache(GetCurrentProcess(), site, 6);
                dbg("[bridge] patch_engine_runcb: site 2 → bb imm32 90  (ebx=%p)\n", runcb);
            }
        }
    }
}

static DWORD __attribute__((stdcall)) iat_watcher_thread(LPVOID arg) {
    (void)arg;
    // Wait for engine.dll to actually be loaded (it loads after us).
    while (g_iat_watcher_run && !g_engine_hmodule) {
        g_engine_hmodule = GetModuleHandleA("engine.dll");
        if (!g_engine_hmodule) Sleep(100);
    }
    if (!g_iat_watcher_run) return 0;
    dbg("[bridge] IAT watcher: engine.dll @ %p — caching targets\n", g_engine_hmodule);

    // Hot-patch engine.dll's references to the SteamAPI_RunCallbacks IAT
    // slot — definitively immune to IAT zeroing from this point forward.
    patch_engine_runcb_refs();

    // Cache the expected target for each slot (our exports' real addresses).
    for (unsigned i = 0; i < sizeof g_iat_slots / sizeof g_iat_slots[0]; i++) {
        g_iat_slots[i].cached_target = (void*)GetProcAddress(g_self_hmodule, g_iat_slots[i].exp_name);
        void **slot = (void**)((char*)g_engine_hmodule + g_iat_slots[i].offset);
        if (*slot && !g_iat_slots[i].cached_target) g_iat_slots[i].cached_target = *slot;
    }

    // L4D2-launcher patch: write-protect was tried and reverted — even
    // though the IAT page is reportedly PAGE_READONLY at runtime, our
    // explicit VirtualProtect call destabilized SP rendering (frequent
    // black flashes).  Likely a Wine TLB / syscall side-effect.  Keep
    // polling-only.  Restoration path below also restores oldprot rather
    // than forcing READONLY, to minimize VirtualProtect churn.
    void *iat_page = (void*)(((unsigned)g_engine_hmodule + g_iat_slots[0].offset) & ~0xFFFu);
    (void)iat_page; // not used at watcher start anymore

    unsigned tick = 0;
    unsigned heartbeat = 0;
    while (g_iat_watcher_run) {
        Sleep(1);
        tick++;
        // Periodic heartbeat so we can confirm the watcher is alive even
        // when no restores fire.  Once every ~30 seconds.
        if ((tick & 0x7FFFu) == 0) {
            heartbeat++;
            dbg("[bridge] watcher heartbeat #%u (ticks=%u)\n", heartbeat, tick);
        }
        for (unsigned i = 0; i < sizeof g_iat_slots / sizeof g_iat_slots[0]; i++) {
            void **slot = (void**)((char*)g_engine_hmodule + g_iat_slots[i].offset);
            if (*slot != 0) continue;
            void *exp = g_iat_slots[i].cached_target;
            if (!exp) continue;

            DWORD oldprot;
            void *page = (void*)((unsigned)slot & ~0xFFFu);
            if (VirtualProtect(page, 0x1000, PAGE_READWRITE, &oldprot)) {
                *slot = exp;
                DWORD ignore;
                VirtualProtect(page, 0x1000, oldprot, &ignore);
                dbg("[bridge] watcher: restored engine.dll IAT[%s] = %p (tick %u)\n",
                    g_iat_slots[i].exp_name, exp, tick);
            }
        }
        // Verify our engine.dll .text patches are still in place.  If the
        // writer reverts them (as we suspect — crashes continued at the
        // same EIP despite the first patch attempt), re-apply.
        unsigned char *site1 = (unsigned char*)g_engine_hmodule + 0x83a07;
        if (site1[0] != 0xe8) {  // patched form starts with e8
            dbg("[bridge] watcher: site 1 reverted (now %02x %02x ...) — re-patching (tick %u)\n",
                site1[0], site1[1], tick);
            patch_engine_runcb_refs();
        }
    }
    return 0;
}

static void try_patch_vgui2(void) {
    HMODULE k32 = GetModuleHandleA("kernel32.dll");
    if (!k32) return;
    void *noop_enc = encode_ptr(k32, (void*)noop_handler);
    try_init_engine_bitbuf_lut();

    // First do vgui2 specially — its Fls slots get real Wine pointers, not noop.
    if (!(g_patched_mask & 1u)) {
        HMODULE v = GetModuleHandleA("vgui2.dll");
        if (v) {
            void *FlsAlloc    = (void*)GetProcAddress(k32, "FlsAlloc");
            void *FlsSetValue = (void*)GetProcAddress(k32, "FlsSetValue");
            void *FlsGetValue = (void*)GetProcAddress(k32, "FlsGetValue");
            void *FlsFree     = (void*)GetProcAddress(k32, "FlsFree");
            if (FlsAlloc && FlsSetValue && FlsGetValue && FlsFree) {
                DWORD old_prot = 0;
                void *page = (void*)((char*)v + 0x5A000);
                if (VirtualProtect(page, 0x3000, PAGE_READWRITE, &old_prot)) {
                    void **fls = (void**)((char*)v + 0x5B8F0);
                    fls[0] = encode_ptr(k32, FlsAlloc);
                    fls[1] = encode_ptr(k32, FlsSetValue);
                    fls[2] = encode_ptr(k32, FlsGetValue);
                    fls[3] = encode_ptr(k32, FlsFree);
                    DWORD ignore;
                    VirtualProtect(page, 0x3000, old_prot, &ignore);
                    dbg("[bridge] vgui2 Fls slots populated (FlsSetValue=%p)\n",
                        FlsSetValue);
                }
            }
            try_patch_one_dll(k32, &g_dll_slots[0], 0, noop_enc);
        }
    }

    // Then walk every other game DLL.
    unsigned n = sizeof(g_dll_slots) / sizeof(g_dll_slots[0]);
    for (unsigned i = 1; i < n; i++) {
        try_patch_one_dll(k32, &g_dll_slots[i], i, noop_enc);
    }
}

// ─── DLL entry point (no CRT) ────────────────────────────────────────────────
__attribute__((stdcall)) BOOL _DllMainCRTStartup(HINSTANCE h, DWORD r, LPVOID rv) {
    (void)rv;
    if (r == DLL_PROCESS_ATTACH) {
        g_self_hmodule = (HMODULE)h;
        InitializeCriticalSection(&g_rpc_lock);
        g_lock_init = 1;
        dbg("[bridge] DLL attach (hModule=%p)\n", h);
        // Pin steam_api.dll so the OS refcount never drops to 0.  Source
        // engine's matchmaking flow appears to trigger something (Source
        // DRM, or matchmaking.dll defensive cleanup, or a Wine quirk on
        // PE module unload) that zeros engine.dll's IAT entries for our
        // exports.  The fingerprint matches what Wine does when a DLL's
        // refcount hits zero: zero out the IAT entries of every dependent
        // module.  Calling LoadLibraryA on ourselves +3 times ensures the
        // refcount stays well above zero even after multiple FreeLibrary
        // calls from anywhere — so the unload-zeros-IATs path never fires.
        // GetModuleHandle wouldn't increment the refcount, LoadLibraryA does.
        for (int pins = 0; pins < 3; pins++) {
            HMODULE pinned = LoadLibraryA("steam_api.dll");
            if (!pinned) { dbg("[bridge] pin %d: LoadLibraryA returned NULL\n", pins); break; }
            dbg("[bridge] pinned steam_api.dll #%d (hModule=%p)\n", pins, pinned);
        }

        // Launch the IAT watcher thread.  It polls engine.dll's IAT entries
        // for our exports every 1ms and restores any that get zeroed.  Don't
        // call CreateThread from DllMain ATTACH (loader lock); defer via a
        // short Sleep + spawn at first SteamAPI_Init call instead — but the
        // CreateThread API itself is usable here, just risky for OS-wide
        // calls.  We use minimal calls and the thread's first action is
        // Sleep, which lets DllMain return cleanly before the thread does
        // anything significant.
        g_iat_watcher_run = 1;
        HANDLE wt = CreateThread(NULL, 0, iat_watcher_thread, NULL, 0, NULL);
        if (wt) { dbg("[bridge] IAT watcher thread spawned (handle=%p)\n", wt); CloseHandle(wt); }
        else dbg("[bridge] IAT watcher CreateThread failed\n");
        // vgui2 might already be in the loader chain when our DllMain runs;
        // try once here. If not loaded yet, RunCallbacks will retry every
        // frame until vgui2 appears. We avoid spawning a separate thread —
        // CreateThread before all DLLs are initialised destabilises Wine 7.7.
        try_patch_vgui2();
    } else if (r == DLL_PROCESS_DETACH) {
        g_iat_watcher_run = 0;  // signal watcher to exit
        if (g_sock != INVALID_SOCKET) { closesocket(g_sock); g_sock = INVALID_SOCKET; }
        WSACleanup();
        if (g_lock_init) { DeleteCriticalSection(&g_rpc_lock); g_lock_init = 0; }
    }
    return TRUE;
}

